const Glyph *findGlyph(char ch) {
    for (const auto &glyph : kFont) {
        if (glyph.ch == ch) return &glyph;
    }
    return &kFont[sizeof(kFont) / sizeof(kFont[0]) - 1];
}

void drawText(Scene2D *scene, const char *text, int x, int y, int scale, Color color) {
    for (const char *p = text; *p; ++p) {
        const Glyph *glyph = findGlyph(*p);
        for (int row = 0; row < 7; ++row) {
            for (int col = 0; col < 5; ++col) {
                if (glyph->rows[row] & (1u << (4 - col))) {
                    scene->DrawRectangle(x + col * scale, y + row * scale,
                                         scale, scale, color);
                }
            }
        }
        x += 6 * scale;
    }
}

void drawSplash(Scene2D *scene) {
    const Color background = {13, 16, 31};
    const Color red = {239, 45, 71};
    const Color pale = {244, 246, 250};
    const Color blue = {68, 190, 255};
    const Color shadow = {34, 38, 57};

    scene->FrameBufferFill(background);
    scene->DrawRectangle(0, 0, 1920, 14, red);
    scene->DrawRectangle(0, 1066, 1920, 14, red);

    // Framed, high-contrast pixel mark.
    scene->DrawRectangle(832, 208, 256, 256, red);
    scene->DrawRectangle(850, 226, 220, 220, shadow);
    scene->DrawRectangle(870, 246, 180, 180, background);
    drawText(scene, "P", 923, 264, 24, pale);
    scene->DrawRectangle(896, 402, 128, 8, blue);

    drawText(scene, "PSYCH ENGINE", 528, 540, 12, pale);
    drawText(scene, "NATIVE BOOTSTRAP TEST", 645, 685, 5, blue);
    drawText(scene, "PS4 CI BUILD", 780, 755, 5, pale);
}
